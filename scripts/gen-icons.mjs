// Collects every "mdi:name" used in src/ and writes src/core/icons.ts with the
// matching @mdi/js paths (no icon font or CDN at runtime). Run: npm run icons
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import * as mdi from "@mdi/js";

const root = new URL("../src/", import.meta.url).pathname;
const files = [];
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) walk(path);
    else if (path.endsWith(".ts") && !path.endsWith("icons.ts")) files.push(path);
  }
};
walk(root);
const names = new Set();
for (const file of files) {
  for (const m of readFileSync(file, "utf8").matchAll(/mdi[:-]([a-z0-9]+(?:-[a-z0-9]+)*)/g)) names.add(m[1]);
}
const camel = (n) => "mdi" + n.split("-").map((s) => s[0].toUpperCase() + s.slice(1)).join("");
const found = [...names].filter((n) => mdi[camel(n)]).sort();
const missing = [...names].filter((n) => !mdi[camel(n)]);
if (missing.length) console.warn("Unknown icons:", missing.join(", "));
writeFileSync(
  join(root, "core", "icons.ts"),
  "// GENERATED by scripts/gen-icons.mjs – every mdi icon used in src/.\nimport {\n" +
    found.map((n) => `  ${camel(n)},`).join("\n") +
    '\n} from "@mdi/js";\n\nexport const ICONS: Record<string, string> = {\n' +
    found.map((n) => `  "mdi:${n}": ${camel(n)},`).join("\n") +
    "\n};\n",
);
console.log(`${found.length} icons`);
